%% Local functions
function [lo,hi]=wilson95(k,n)
if n<=0 || isnan(k), lo=NaN; hi=NaN; return; end
z=1.95996398454005; p=k/n; d=1+z^2/n;
c=(p+z^2/(2*n))/d;
h=z/d*sqrt(p*(1-p)/n+z^2/(4*n^2));
lo=max(0,c-h); hi=min(1,c+h);
end

function T=addRateCI(T)
vars=string(T.Properties.VariableNames);
for rateName=["FeasibleRate","TopologyRecoveryRate","BudgetHitRate"]
    if any(vars==rateName) && any(vars=="n")
        r=T.(rateName); n=T.n; lo=nan(height(T),1); hi=lo;
        for j=1:height(T)
            if ~isnan(r(j))
                k=round(r(j)*n(j)); [lo(j),hi(j)]=wilson95(k,n(j));
            end
        end
        T.([char(rateName) '_CI95_L'])=lo;
        T.([char(rateName) '_CI95_U'])=hi;
    end
end
end

function H=harmonizeGA(G,Ttemplate)
% Return G with the same variables/order as direct-GA table, filling absent fields.
H=table();
for i=1:numel(Ttemplate.Properties.VariableNames)
    v=Ttemplate.Properties.VariableNames{i};
    if ismember(v,G.Properties.VariableNames)
        H.(v)=G.(v);
    elseif strcmp(v,'MedianPolishedObjective') && ismember('MedianObjective',G.Properties.VariableNames)
        H.(v)=G.MedianObjective;
    else
        if iscell(Ttemplate.(v)) || isstring(Ttemplate.(v))
            H.(v)=strings(height(G),1);
        else
            H.(v)=nan(height(G),1);
        end
    end
end
if iscell(H.Configuration)
    H.Configuration(:) = {'GA_localNLP'};
elseif isstring(H.Configuration)
    H.Configuration(:) = "GA_localNLP";
elseif iscategorical(H.Configuration)
    H.Configuration(:) = categorical({'GA_localNLP'});
else
    error('Unexpected Configuration variable type: %s', class(H.Configuration));
end
end

function R=summarizeReef(X)
configs=["Reef_60","Nominal","Reef_240"]'; vals=[60;120;240];
R=table();
for q=1:3
    Z=X(string(X.Configuration)==configs(q),:);
    n=height(Z);
    % Flexible variable-name matching for run tables.
    feas=getcol(Z,["Feasible","IsFeasible","feasible"]);
    top=getcol(Z,["TopologyRecovered","TopologyRecovery","CorrectTopology"]);
    obj=getcol(Z,["Objective","RawObjective","FinalObjective"]);
    oc=getcol(Z,["OracleCalls","TotalOracleCalls","BudgetOracleCalls"]);
    nlp=getcol(Z,["LocalNLPCalls","NLPCalls"]);
    it=getcol(Z,["Iterations","Iteration"]);
    rt=getcol(Z,["Runtime","Runtime_s"]);
    gap=100*abs(obj-refObjective())/refObjective();
    row=table(configs(q),"ReefSize",vals(q),n,mean(feas),mean(top),median(obj),median(gap), ...
        median(oc),iqr(oc),median(nlp),median(it),median(rt),iqr(rt), ...
        'VariableNames',{'Configuration','Parameter','ParameterValue','n','FeasibleRate', ...
        'TopologyRecoveryRate','MedianObjective','MedianAbsGapPercent','MedianOracleCalls', ...
        'IQROracleCalls','MedianLocalNLPCalls','MedianIterations','MedianRuntime','IQRRuntime'});
    R=[R;row]; %#ok<AGROW>
end
end

function x=getcol(T,candidates)
vars=string(T.Properties.VariableNames);
for c=candidates
    ix=find(strcmpi(vars,c),1);
    if ~isempty(ix), x=T.(T.Properties.VariableNames{ix}); return; end
end
error('Could not find any of these columns: %s',strjoin(candidates,', '));
end

function r=refObjective()
r=68.009744051065;
end
